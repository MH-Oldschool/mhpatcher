#!/bin/sh
# Generates src/dnas/baked_data.h from data/. Needs xxd.
set -e
cd "$(dirname "$0")/.."
out=src/dnas/baked_data.h
{
  echo "/* Generated by tools/gen_baked.sh from data/. */"
  echo "#ifndef BAKED_DATA_H"
  echo "#define BAKED_DATA_H"
  echo "#include <stdint.h>"
  for pair in \
      mh2_blob:data/mh2_blob.raw \
      mh2_hdr_plain:data/mh2_hdr_plain.bin \
      mh2_meta:data/mh2_meta.bin \
      mh2_payload:data/mh2_payload.bin \
      mhg_blob:data/mhg_blob.raw \
      mhg_hdr_plain:data/mhg_hdr_plain.bin \
      mhg_meta:data/mhg_meta.bin; do
    name=${pair%%:*}; file=${pair#*:}
    echo "static const uint8_t ${name}[] = {"
    xxd -i < "$file" | sed 's/^/  /'
    echo "};"
  done
  echo "#endif"
} > "$out"
echo "wrote $out"
