#!/usr/bin/env python3
# Converts MH1's NTGUI2/bin/bg.rgb (640x448 RGB) into the 256x256 CT16
# backdrop in src/ui/bg_data.h.
#   python3 -I tools/make_bg.py path/to/bg.rgb
import os, sys
from PIL import Image

if len(sys.argv) != 2:
    sys.exit("usage: make_bg.py path/to/bg.rgb")
HERE = os.path.dirname(os.path.abspath(__file__))
SRC  = sys.argv[1]
OUT  = os.path.join(HERE, "..", "src", "ui", "bg_data.h")
W, H = 256, 256

raw = open(SRC, "rb").read()
im = Image.frombytes("RGB", (640, 448), raw).resize((W, H), Image.LANCZOS)
# brighten the dark night scene a little
im = Image.eval(im, lambda v: min(255, int(v * 1.12 + 18)))
px = im.load()

def to5551(r, g, b):
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10) | 0x8000

with open(OUT, "w") as f:
    f.write("/* Generated by tools/make_bg.py. */\n")
    f.write("#ifndef BG_DATA_H\n#define BG_DATA_H\n#include <stdint.h>\n")
    f.write(f"#define BG_W {W}\n#define BG_H {H}\n")
    f.write(f"static const uint16_t bg_pixels[{W*H}] = {{\n")
    vals = []
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            vals.append(to5551(r, g, b))
    for i in range(0, len(vals), 24):
        f.write(" " + ",".join(str(v) for v in vals[i:i+24]) + ",\n")
    f.write("};\n#endif\n")
print(f"wrote {OUT}: {W}x{H} RGBA5551 ({W*H*2} bytes)")
